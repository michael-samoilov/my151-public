"""Write docs/credits/pokeapi-delivery.json: which shown sprite files PokéAPI delivers.

A shown file (a row of docs/credits/sprite-evidence.json) counts as delivered
through PokéAPI when its pixels equal a PNG in PokéAPI's sprites repository:
any PNG under sprites/pokemon at the pinned commit, or an earlier version of
the file at the same path (the importer took some files before PokéAPI
replaced them). Pixels compare as the ledger compares them: RGBA after the
transparent margins are trimmed, with every fully transparent pixel equal.

scripts/credits/bundle-credits.ts reads the result for the PokéAPI entry's
counts. It fails when a ledger row is missing here or has another sha256, so
a changed or added sprite needs a new run.

The run needs the network once, for the clone. Requires Pillow.

    git clone --filter=blob:none --no-checkout https://github.com/PokeAPI/sprites pokeapi-sprites
    git -C pokeapi-sprites sparse-checkout set --no-cone '/sprites/pokemon/*.png' \\
      '/sprites/pokemon/female/*.png' '/sprites/pokemon/shiny/*.png' \\
      '/sprites/pokemon/versions/generation-v/black-white/*.png' \\
      '/sprites/pokemon/versions/generation-v/black-white/female/*.png' \\
      '/sprites/pokemon/versions/generation-v/black-white/shiny/*.png'
    git -C pokeapi-sprites checkout <pokeapiCommit of docs/credits/pokeapi-form-sources.json>
    python3 scripts/credits/pokeapi-delivery.py pokeapi-sprites
"""
import hashlib
import io
import json
import subprocess
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs/credits/pokeapi-delivery.json'
APP_DIR = 'public/sprites/pokemon/'


def pixels(data: bytes) -> str:
    image = Image.open(io.BytesIO(data)).convert('RGBA')
    raw = bytearray(image.tobytes())
    for at in range(3, len(raw), 4):
        if raw[at] == 0:
            raw[at - 3:at] = b'\0\0\0'
    image = Image.frombytes('RGBA', image.size, bytes(raw))
    box = image.getbbox()
    if box:
        image = image.crop(box)
    return hashlib.sha256(f'{image.size}'.encode() + image.tobytes()).hexdigest()


def git(clone: Path, *args: str) -> bytes:
    return subprocess.run(['git', '-C', str(clone), *args], check=True, capture_output=True).stdout


def main() -> None:
    clone = Path(sys.argv[1]).resolve()
    commit = json.loads((ROOT / 'docs/credits/pokeapi-form-sources.json').read_text())['pokeapiCommit']
    head = git(clone, 'rev-parse', 'HEAD').decode().strip()
    if head != commit:
        sys.exit(f'{clone} is at {head}; check out {commit}.')

    by_path = {path.relative_to(clone).as_posix(): pixels(path.read_bytes())
               for path in sorted((clone / 'sprites/pokemon').rglob('*.png'))}
    pinned: dict[str, str] = {}
    for path, key in by_path.items():
        pinned.setdefault(key, path)

    ledger = json.loads((ROOT / 'docs/credits/sprite-evidence.json').read_text())
    files = {}
    for row in sorted(ledger, key=lambda r: r['file']):
        file = row['file']
        key = pixels((ROOT / file).read_bytes())
        same = 'sprites/pokemon/' + file.removeprefix(APP_DIR)
        found = same if by_path.get(same) == key else pinned.get(key)
        match = f'{commit[:8]}:{found}' if found else None
        if match is None:
            for old in git(clone, 'log', '--all', '--format=%H', '--', same).decode().split():
                try:
                    if pixels(git(clone, 'show', f'{old}:{same}')) == key:
                        match = f'{old[:8]}:{same}'
                        break
                except subprocess.CalledProcessError:
                    continue
        files[file] = {'sha256': row['sha256'], 'pokeapi': match}

    lines = ',\n'.join(f'  {json.dumps(file)}: {json.dumps(entry, ensure_ascii=False)}' for file, entry in files.items())
    note = ('Generated by scripts/credits/pokeapi-delivery.py from docs/credits/sprite-evidence.json and a clone of '
            'https://github.com/PokeAPI/sprites. "pokeapi" names the PokéAPI commit and file with the same pixels, '
            'or is null. Do not edit.')
    OUT.write_text(f'{{\n "note": {json.dumps(note, ensure_ascii=False)},\n "pokeapiCommit": "{commit}",\n "files": {{\n{lines}\n }}\n}}\n')
    matched = sum(1 for entry in files.values() if entry['pokeapi'])
    print(f'pokeapi-delivery: {matched} of {len(files)} shown files match a PokéAPI file.')


if __name__ == '__main__':
    main()
