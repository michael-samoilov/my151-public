

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { LANGUAGE_IDS, ensureCsvs, readCsv } from './pokeapi';
import type { IdMapEntry } from './propose-id-map';

export const ID_MAP_FIXTURE_PATH = 'scripts/i18n/id-map-fixture.json';

export interface IdMapFixture {
  readonly source: string;
  readonly pokemon: Record<string, { identifier: string; speciesId: number }>;
  readonly forms: number[];
  readonly species: Record<string, { identifier: string; en: string }>;
}

function main(): void {
  void ensureCsvs().then(() => {
    const { entries } = JSON.parse(readFileSync('scripts/i18n/pokemon-id-map.json', 'utf8')) as {
      entries: IdMapEntry[];
    };

    const pokemonRows = new Map(readCsv('pokemon').map((r) => [Number(r.id), r]));
    const formIds = new Set(readCsv('pokemon_forms').map((r) => Number(r.id)));
    const speciesRows = new Map(readCsv('pokemon_species').map((r) => [Number(r.id), r.identifier]));
    const englishNames = new Map<number, string>();
    for (const r of readCsv('pokemon_species_names')) {
      if (Number(r.local_language_id) === LANGUAGE_IDS.en) {
        englishNames.set(Number(r.pokemon_species_id), r.name);
      }
    }

    const pokemon: IdMapFixture['pokemon'] = {};
    const forms: number[] = [];
    const species: IdMapFixture['species'] = {};

    for (const e of entries) {

      const row = pokemonRows.get(e.appId);
      if (row) pokemon[e.appId] = { identifier: row.identifier, speciesId: Number(row.species_id) };

      if (formIds.has(e.formId)) forms.push(e.formId);
      const identifier = speciesRows.get(e.speciesId);
      const en = englishNames.get(e.speciesId);
      if (identifier && en) species[e.speciesId] = { identifier, en };

      if (row) {
        const upstreamSpecies = Number(row.species_id);
        const ui = speciesRows.get(upstreamSpecies);
        const ue = englishNames.get(upstreamSpecies);
        if (ui && ue && !species[upstreamSpecies]) species[upstreamSpecies] = { identifier: ui, en: ue };
      }
    }

    const out: IdMapFixture = {
      source:
        'Generated by `npm run i18n:fixture` from PokeAPI data/v2/csv ' +
        '(pokemon, pokemon_forms, pokemon_species, pokemon_species_names). ' +
        'Only the rows scripts/i18n/pokemon-id-map.json references.',
      pokemon,
      forms: [...new Set(forms)].sort((a, b) => a - b),
      species,
    };

    const rows = (o: object) =>
      Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
    writeFileSync(
      ID_MAP_FIXTURE_PATH,
      `{\n "source": ${JSON.stringify(out.source)},\n` +
        ` "pokemon": {\n${rows(out.pokemon)}\n },\n` +
        ` "forms": ${JSON.stringify(out.forms)},\n` +
        ` "species": {\n${rows(out.species)}\n }\n}\n`,
    );
    console.log(
      `  ${Object.keys(pokemon).length} pokemon rows, ${out.forms.length} forms, ` +
        `${Object.keys(species).length} species -> ${ID_MAP_FIXTURE_PATH}`,
    );
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  void main();
}
