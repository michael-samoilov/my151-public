/** A row of tiles under one heading in the browser. Archetype-defined subgroups
 *  may pin shiny sprites; the auto-generated by-generation ones never do. Both
 *  sources share this shape so the render path doesn't have to narrow a union. */
interface BrowserSubgroup {
  label: string;
  pokemonIds: number[];
  shinyIds?: number[];
}

/** Off-screen subgroup blocks skip layout and paint. The results list runs to
 *  ~1,100 tiles with no virtualization, so this is what keeps a re-render from
 *  laying out every one of them. `auto` for the intrinsic size means the
 *  browser reuses each block's last rendered height, so the scrollbar stays
 *  stable after the first pass. */
const SUBGROUP_BLOCK_STYLE: React.CSSProperties = {
  contentVisibility: 'auto',
  containIntrinsicSize: 'auto 600px',
};

/** One evo-line entry of a subgroup's render model, shaped for EvoLineGrid. */
interface SubgroupGridGroup {
  key: string;
  members: Pokemon[];
  matchedIds: Set<number>;
}

export function PokemonBrowser() {
  const searchQuery = usePokedexStore((s) => s.searchQuery);
  const setSearchQuery = usePokedexStore((s) => s.setSearchQuery);
  const activeCategory = usePokedexStore((s) => s.activeCategoryFilter);
  const setCategoryFilter = usePokedexStore((s) => s.setCategoryFilter);
  const activeArchetype = usePokedexStore((s) => s.activeArchetypeFilter);
  const setArchetypeFilter = usePokedexStore((s) => s.setArchetypeFilter);
  const typeFilter = usePokedexStore((s) => s.typeFilter);
  const setTypeFilter = usePokedexStore((s) => s.setTypeFilter);
  const typeFilterMode = usePokedexStore((s) => s.typeFilterMode);
  const setTypeFilterMode = usePokedexStore((s) => s.setTypeFilterMode);
  const toggleType = usePokedexStore((s) => s.toggleType);
  const generationFilter = usePokedexStore((s) => s.generationFilter);
  const setGenerationFilter = usePokedexStore((s) => s.setGenerationFilter);
  const toggleGeneration = usePokedexStore((s) => s.toggleGeneration);
  const shapeFilter = usePokedexStore((s) => s.shapeFilter);
  const setShapeFilter = usePokedexStore((s) => s.setShapeFilter);
  const toggleShape = usePokedexStore((s) => s.toggleShape);
  const colorFilter = usePokedexStore((s) => s.colorFilter);
  const setColorFilter = usePokedexStore((s) => s.setColorFilter);
  const toggleColor = usePokedexStore((s) => s.toggleColor);
  const eggGroupFilter = usePokedexStore((s) => s.eggGroupFilter);
  const setEggGroupFilter = usePokedexStore((s) => s.setEggGroupFilter);
  const toggleEggGroup = usePokedexStore((s) => s.toggleEggGroup);
  const evoLineSizeFilter = usePokedexStore((s) => s.evoLineSizeFilter);
  const setEvoLineSizeFilter = usePokedexStore((s) => s.setEvoLineSizeFilter);
  const sections = usePokedexStore((s) => s.sections);
  const activeSection = usePokedexStore((s) => s.activeSection);
  const addToSection = usePokedexStore((s) => s.addToSection);
  const t = useT();
  const tn = useTn();
  const [openSheet, setOpenSheet] = useState<FilterSheet>(null);
  const [sheetH, setSheetH] = useState(0);
  const isDesktop = useIsDesktop();
  const gridMaxW = useTileGridMaxWidth(6, 0, 0);
  const gridMaxW3 = useTileGridMaxWidth(3, 0, 0);

  // Staged selection: pokemon selected but not yet committed
  const [stagedIds, setStagedIds] = useState<number[]>([]);
  const stagedSet = useMemo(() => new Set(stagedIds), [stagedIds]);
  // Staged removals: assigned pokemon the user wants to remove (pending confirmation)
  const [removalStagedIds, setRemovalStagedIds] = useState<number[]>([]);
  const removalStagedSet = useMemo(() => new Set(removalStagedIds), [removalStagedIds]);
  const prevSectionRef = useRef(activeSection);
  const removeEvoLine = usePokedexStore((s) => s.removeEvoLine);

  const setMobileBrowserOpen = usePokedexStore((s) => s.setMobileBrowserOpen);
  const setActiveSection = usePokedexStore((s) => s.setActiveSection);

  const assignedIds = useMemo(
    () => new Set(Object.values(sections).flat()),
    [sections]
  );

  // Reset staged + close filter sheet when activeSection changes
  useEffect(() => {
    if (activeSection !== prevSectionRef.current) {
      setStagedIds([]);
      setRemovalStagedIds([]);
      if (!activeSection) setOpenSheet(null);
      prevSectionRef.current = activeSection;
    }
  }, [activeSection]);

  const handleToggleStage = useCallback((memberIds: number[]) => {
    if (isDesktop && activeSection) {
      // Desktop: instantly add unassigned pokemon (no staging)
      const newIds = memberIds.filter(id => !assignedIds.has(id));
      if (newIds.length > 0) {
        addToSection(activeSection, newIds);
        // Scroll the build page to the target section
        window.dispatchEvent(new CustomEvent('scroll-to-section', { detail: activeSection }));
      }
      return;
    }
    setStagedIds(prev => {
      const prevSet = new Set(prev);
      const allStaged = memberIds.every(id => prevSet.has(id));
      if (allStaged) {
        // Unstage: remove members, but keep shared pre-evolutions that
        // are still needed by another staged exclusive form.
        const exclusiveIds = new Set(memberIds.flatMap(id => getExclusiveForms(id)));
        const otherStagedExclusives = prev.filter(id => exclusiveIds.has(id) && !memberIds.includes(id));
        if (otherStagedExclusives.length > 0) {
          // Another exclusive form is staged — only remove the exclusive
          // member(s) from this line, keep shared pre-evolutions.
          const removeSet = new Set(memberIds.filter(id => exclusiveIds.has(id) || getExclusiveForms(id).length > 0));
          return prev.filter(id => !removeSet.has(id));
        }
        const removeSet = new Set(memberIds);
        return prev.filter(id => !removeSet.has(id));
      } else {
        // Stage: add new members, auto-remove exclusive forms.
        const exclusiveRemovals = new Set(memberIds.flatMap(id => getExclusiveForms(id)));
        const cleaned = exclusiveRemovals.size > 0
          ? prev.filter(id => !exclusiveRemovals.has(id))
          : prev;
        const cleanedSet = new Set(cleaned);
        const toAdd = memberIds.filter(id => !cleanedSet.has(id));
        return [...cleaned, ...toAdd];
      }
    });
  }, [isDesktop, activeSection, assignedIds, addToSection]);

  const handleToggleRemoval = useCallback((memberIds: number[]) => {
    setRemovalStagedIds(prev => {
      const prevSet = new Set(prev);
      const allStaged = memberIds.every(id => prevSet.has(id));
      if (allStaged) {
        const removeSet = new Set(memberIds);
        return prev.filter(id => !removeSet.has(id));
      } else {
        const toAdd = memberIds.filter(id => !prevSet.has(id));
        return [...prev, ...toAdd];
      }
    });
  }, []);

  const handleSubmitStaged = useCallback(() => {
    if (isDesktop) {
      // Desktop: only process removals (adds are instant)
      if (removalStagedIds.length > 0) {
        const removed = new Set<number>();
        for (const id of removalStagedIds) {
          if (removed.has(id)) continue;
          for (const [sectionId, ids] of Object.entries(sections)) {
            if (ids.includes(id)) {
              removeEvoLine(sectionId, id);
              break;
            }
          }
          removed.add(id);
        }
        setRemovalStagedIds([]);
      }
      return;
    }
    const targetSection = activeSection ?? 'other';
    const newIds = stagedIds.filter(id => !assignedIds.has(id));
    if (newIds.length > 0) addToSection(targetSection, newIds);
    // Process removals: find each removal-staged pokemon's section and remove
    if (removalStagedIds.length > 0) {
      const removed = new Set<number>();
      for (const id of removalStagedIds) {
        if (removed.has(id)) continue;
        for (const [sectionId, ids] of Object.entries(sections)) {
          if (ids.includes(id)) {
            removeEvoLine(sectionId, id);
            break;
          }
        }
        removed.add(id);
      }
    }
    setStagedIds([]);
    setRemovalStagedIds([]);
    setMobileBrowserOpen(false);
    setActiveSection(null);
  }, [isDesktop, stagedIds, removalStagedIds, activeSection, assignedIds, sections, addToSection, removeEvoLine, setMobileBrowserOpen, setActiveSection]);

  const handleDesktopClose = useCallback(() => {
    setStagedIds([]);
    setRemovalStagedIds([]);
    setActiveSection(null);
  }, [setActiveSection]);

  const sectionName = activeSection
    ? sectionLabel(activeSection)
    : null;

  // All inputs to the results grid go through one memoized options object
  // read at deferred priority. The urgent render after a keystroke or chip
  // tap repaints only the header controls; the expensive filter → group →
  // grid work runs in an interruptible deferred render, and fast typing
  // cancels the intermediate ones. The object must be memoized before it is
  // deferred — an inline literal would never compare equal.
  const filterOptions = useMemo(() => ({
    search: searchQuery,
    category: activeCategory,
    archetype: activeArchetype,
    types: typeFilter,
    typeMode: typeFilterMode,
    generations: generationFilter,
    shapes: shapeFilter,
    colors: colorFilter,
    eggGroups: eggGroupFilter,
    evoLineSize: evoLineSizeFilter,
  }), [searchQuery, activeCategory, activeArchetype, typeFilter, typeFilterMode, generationFilter, shapeFilter, colorFilter, eggGroupFilter, evoLineSizeFilter]);
  const deferredOptions = useDeferredValue(filterOptions);
  const groups = useFilteredPokemonGrouped(deferredOptions);

  const totalCount = useMemo(() => groups.reduce((sum, g) => sum + g.members.length, 0), [groups]);

  // Header chips read the urgent values so taps echo instantly.
  const activeCategoryDef = activeCategory
    ? CATEGORIES.find((c) => c.id === activeCategory)
    : null;
  const categoryName = activeCategoryDef ? categoryLabel(activeCategoryDef.id) : null;
  const activeArchetypeDef = activeArchetype
    ? ARCHETYPES.find((a) => a.id === activeArchetype)
    : null;
  const archetypeName = activeArchetypeDef ? archetypeLabel(activeArchetypeDef.id) : null;

  // The results grid derives everything from the same deferred snapshot as
  // `groups`, so its tree stays internally consistent while a deferred
  // render is still pending.
  const gridCategoryDef = deferredOptions.category
    ? CATEGORIES.find((c) => c.id === deferredOptions.category)
    : null;
  const gridArchetypeDef = deferredOptions.archetype
    ? ARCHETYPES.find((a) => a.id === deferredOptions.archetype)
    : null;
  const shinyIds = useMemo(
    () => gridArchetypeDef?.shinyIds ? new Set(gridArchetypeDef.shinyIds) : undefined,
    [gridArchetypeDef]
  );
  const spriteOverrides = gridArchetypeDef?.spriteOverrides;

  // Subgroups: custom if archetype/category defines them, otherwise auto-generate by generation
  const effectiveSubgroups = useMemo((): BrowserSubgroup[] => {
    if (gridArchetypeDef?.subgroups) return gridArchetypeDef.subgroups;
    if (gridCategoryDef?.subgroups) return gridCategoryDef.subgroups;

    // For archetypes: group archetype pokemonIds by generation
    // For default/category views: group matched member IDs by generation
    // (using matchedIds ensures e.g. Baby Pokemon category groups by the baby's gen,
    //  not by the gen of evolved forms like Hitmonlee)
    const sourceIds = gridArchetypeDef
      ? gridArchetypeDef.pokemonIds
      : groups.flatMap(g => [...g.matchedIds]);

    const genMap = new Map<number, number[]>();
    for (const id of sourceIds) {
      const p = getPokemonById(id);
      if (!p) continue;
      if (!genMap.has(p.generation)) genMap.set(p.generation, []);
      genMap.get(p.generation)!.push(id);
    }

    return [...genMap.entries()]
      .sort((a, b) => a[0] - b[0])
      .map(([gen, ids]) => ({ label: t('browser.subgroupGeneration', { gen }), pokemonIds: ids }));
    // gridCategoryDef is read for its `.subgroups`; it's a stable .find() over
    // the static CATEGORIES array, so it only changes when the category does.
  }, [gridArchetypeDef, gridCategoryDef, groups, t]);

  const toggleEvoSize = (size: number) => {
    if (!evoLineSizeFilter) {
      setEvoLineSizeFilter([size]);
    } else if (evoLineSizeFilter.includes(size)) {
      const next = evoLineSizeFilter.filter(s => s !== size);
      setEvoLineSizeFilter(next.length > 0 ? next : null);
    } else {
      setEvoLineSizeFilter([...evoLineSizeFilter, size]);
    }
  };

  // Gen badges only make sense when subgroups are generation-based.
  // Auto-generated subgroups are always generation-based; custom thematic subgroups (e.g.
  // "volcanic", "gym ace") are not. Cross-gen-evo is an exception: its custom subgroups
  // are labeled by generation, so badges correctly flag members from a different gen.
  const hasCustomSubgroups = !!(gridArchetypeDef?.subgroups || gridCategoryDef?.subgroups);
  const showGenBadges = !hasCustomSubgroups || deferredOptions.archetype === 'cross-gen-evo' || deferredOptions.category === 'starter';

  // Deferred like the grid: the search view and its subgroups must switch
  // together with the `groups` they render.
  const isSearching = deferredOptions.search.trim().length > 0;
  const hasActivePropertyFilters = !!((typeFilter && typeFilter.length > 0) || (generationFilter && generationFilter.length > 0) || (shapeFilter && shapeFilter.length > 0) || (colorFilter && colorFilter.length > 0) || (eggGroupFilter && eggGroupFilter.length > 0) || evoLineSizeFilter);
  const hasActiveBrowseFilters = !!(activeCategory || activeArchetype);
  const hasActiveFilters = hasActivePropertyFilters || hasActiveBrowseFilters;

  const clearPropertyFilters = () => {
    setTypeFilter(null);
    setTypeFilterMode('any');
    setGenerationFilter(null);
    setShapeFilter(null);
    setColorFilter(null);
    setEggGroupFilter(null);
    setEvoLineSizeFilter(null);
  };
  const clearBrowseFilters = () => {
    setCategoryFilter(null);
    setArchetypeFilter(null);
  };

  // When searching, generate subgroups from actual results (ignoring filters)
  const searchSubgroups = useMemo((): BrowserSubgroup[] => {
    if (!isSearching) return [];
    const genMap = new Map<number, number[]>();
    for (const g of groups) {
      for (const m of g.members) {
        if (!genMap.has(m.generation)) genMap.set(m.generation, []);
        genMap.get(m.generation)!.push(m.id);
      }
    }
    return [...genMap.entries()]
      .sort((a, b) => a[0] - b[0])
      .map(([gen, ids]) => ({ label: t('browser.subgroupGeneration', { gen }), pokemonIds: [...new Set(ids)] }));
  }, [isSearching, groups, t]);

  // Per-subgroup render model. This filter/sort/map used to run inline in
  // JSX on every render — the main per-interaction JS cost of this
  // component. Hoisting it also gives EvoLineGrid stable `groups` prop
  // identities, so its internal memo holds across unrelated re-renders.
  const subgroupModels = useMemo(() => {
    const source = isSearching ? searchSubgroups : effectiveSubgroups;
    const dualCols = !isSearching ? gridCategoryDef?.dualColumns : undefined;
    const models: {
      label: string;
      dualCols?: NonNullable<PokemonCategory['dualColumns']>;
      groups?: SubgroupGridGroup[];
      leftGroups?: SubgroupGridGroup[];
      rightGroups?: SubgroupGridGroup[];
      shinyIds?: Set<number>;
      spriteOverrides?: Record<number, string>;
    }[] = [];

    for (const sub of source) {
      const subIdSet = new Set(sub.pokemonIds);
      const matching = groups.filter(g => g.members.some(m => subIdSet.has(m.id)));
      if (matching.length === 0) continue;

      if (!isSearching && gridArchetypeDef) {
        // Archetype view: preserve curated pokemonIds order.
        const orderIdx = new Map<EvolutionGroup, number>();
        for (const g of matching) {
          orderIdx.set(g, sub.pokemonIds.findIndex(id => g.members.some(m => m.id === id)));
        }
        matching.sort((a, b) => orderIdx.get(a)! - orderIdx.get(b)!);
      } else {
        // Default view: sort by lowest matching member's dex number.
        const minId = new Map<EvolutionGroup, number>();
        for (const g of matching) {
          let min = Infinity;
          for (const m of g.members) {
            if (subIdSet.has(m.id) && m.id < min) min = m.id;
          }
          minId.set(g, min);
        }
        matching.sort((a, b) => minId.get(a)! - minId.get(b)!);
      }

      const mapGroup = (group: EvolutionGroup): SubgroupGridGroup => ({
        key: `${sub.label}-${group.chainId}`,
        members: group.members,
        matchedIds: new Set(group.members.filter(m => subIdSet.has(m.id)).map(m => m.id)),
      });

      if (dualCols) {
        const leftIdSet = new Set(dualCols.left.ids);
        const rightIdSet = new Set(dualCols.right.ids);
        models.push({
          label: sub.label,
          dualCols,
          leftGroups: matching.filter(g => g.members.some(m => leftIdSet.has(m.id))).map(mapGroup),
          rightGroups: matching.filter(g => g.members.some(m => rightIdSet.has(m.id))).map(mapGroup),
        });
      } else {
        models.push({
          label: sub.label,
          groups: matching.map(mapGroup),
          shinyIds: isSearching ? undefined : (sub.shinyIds ? new Set(sub.shinyIds) : shinyIds),
          spriteOverrides: isSearching ? undefined : spriteOverrides,
        });
      }
    }
    return models;
  }, [isSearching, searchSubgroups, effectiveSubgroups, groups, gridArchetypeDef, gridCategoryDef, shinyIds, spriteOverrides]);
  const typeKey = typeFilter ? `${typeFilterMode}-${typeFilter.join(',')}` : 'none';
  const genKey = generationFilter ? generationFilter.join(',') : 'none';
  const shapeKey = shapeFilter ? shapeFilter.join(',') : 'none';
  const colorKey = colorFilter ? colorFilter.join(',') : 'none';
  const eggKey = eggGroupFilter ? eggGroupFilter.join(',') : 'none';
  const evoSizeKey = evoLineSizeFilter ? evoLineSizeFilter.join(',') : 'none';

  // Reset the results scroll position when the active filter set changes.
  // This used to be implemented by putting a composite key on the scroll
  // container (forcing React to unmount/remount every child), which made
  // every filter tap rebuild every evo-line card and decode every sprite
  // from scratch — catastrophic for INP. Scrolling the existing node to
  // the top gives the same UX at ~0 ms cost.
  const resultsScrollRef = useRef<HTMLDivElement>(null);
  const resultsResetKey = `${activeCategory ?? 'x'}-${activeArchetype ?? 'none'}-${typeKey}-${genKey}-${shapeKey}-${colorKey}-${eggKey}-${searchQuery}-${evoSizeKey}`;
  useEffect(() => {
    resultsScrollRef.current?.scrollTo({ top: 0, left: 0, behavior: 'auto' });
  }, [resultsResetKey]);

  const browserHeaderRef = useRef<HTMLDivElement>(null);

  // Block vertical touchmove on header to prevent pull-to-refresh mid-browser,
  // but allow horizontal movement so chip rows can scroll sideways.
  useEffect(() => {
    const el = browserHeaderRef.current;
    if (!el) return;
    let startX = 0, startY = 0;
    const onStart = (e: TouchEvent) => {
      startX = e.touches[0].clientX;
      startY = e.touches[0].clientY;
    };
    const block = (e: TouchEvent) => {
      const dx = Math.abs(e.touches[0].clientX - startX);
      const dy = Math.abs(e.touches[0].clientY - startY);
      if (dy > dx) e.preventDefault();
    };
    el.addEventListener('touchstart', onStart, { passive: true });
    el.addEventListener('touchmove', block, { passive: false });
    return () => {
      el.removeEventListener('touchstart', onStart);
      el.removeEventListener('touchmove', block);
    };
  }, []);

  const filterContent = openSheet ? (
    <>
      {openSheet === 'type' && (
        <div className="space-y-2">
          {typeFilter && typeFilter.length >= 2 && (
            <div className="flex items-center gap-2 pb-1">
              <span className="text-[0.6875rem] text-muted-foreground">{t('browser.mode.label')}</span>
              <button type="button"
                onClick={() => setTypeFilterMode('any')}
                className={cn('px-2 py-0.5 rounded text-[0.6875rem] font-medium cursor-pointer transition-colors',
                  typeFilterMode === 'any' ? 'bg-foreground text-background' : 'bg-secondary text-secondary-foreground'
                )}
              >
                {t('browser.mode.any')}
              </button>
              <button type="button"
                onClick={() => setTypeFilterMode('all')}
                className={cn('px-2 py-0.5 rounded text-[0.6875rem] font-medium cursor-pointer transition-colors',
                  typeFilterMode === 'all' ? 'bg-foreground text-background' : 'bg-secondary text-secondary-foreground'
                )}
              >
                {t('browser.mode.all')}
              </button>
              <span className="text-[0.625rem] text-muted-foreground ml-auto">
                {typeFilterMode === 'all' ? t('browser.modeHint.all') : t('browser.modeHint.any')}
              </span>
            </div>
          )}
          <div data-testid="type-filter" className="grid grid-cols-3 gap-1 max-w-sm md:grid-cols-6 md:max-w-2xl mx-auto">
            {TYPE_NAMES.map((type) => {
              const isSelected = typeFilter?.includes(type) ?? false;
              return (
                <button type="button"
                  key={type}
                  onClick={() => toggleType(type)}
                  className="flex items-center justify-center py-0.5 rounded-md cursor-pointer transition-[opacity,scale] duration-150 ease-out active:scale-[0.96]"
                  style={{
                    opacity: typeFilter && typeFilter.length > 0 && !isSelected ? 0.3 : 1,
                  }}
                >
                  <TypeBadge type={type} className="w-[5.625rem]" />
                </button>
              );
            })}
          </div>
        </div>
      )}

      {openSheet === 'generation' && (
        <div className="grid grid-cols-3 gap-1.5">
          {[1, 2, 3, 4, 5, 6, 7, 8, 9].map((gen) => (
            <Button
              key={gen}
              variant={generationFilter?.includes(gen) ? 'default' : 'secondary'}
              className="h-9 text-sm"
              onClick={() => toggleGeneration(gen)}
            >
              {t('browser.genChip', { gen })}
            </Button>
          ))}
        </div>
      )}

      {openSheet === 'shape' && (
        <div className="grid grid-cols-4 md:grid-cols-7 gap-1.5">
          {SHAPE_ORDER.map((shape) => (
            <Button
              key={shape}
              variant={shapeFilter?.includes(shape) ? 'default' : 'secondary'}
              className="h-14 flex flex-col items-center justify-center gap-0.5 px-1"
              onClick={() => toggleShape(shape)}
              title={shapeLabel(shape)}
            >
              <ShapeIcon shape={shape} className="w-5 h-5" />
              <span className="text-[0.5625rem] leading-tight truncate max-w-full">{shapeLabel(shape)}</span>
            </Button>
          ))}
        </div>
      )}

      {openSheet === 'color' && (
        <div className="grid grid-cols-4 md:grid-cols-5 gap-1.5">
          {COLOR_ORDER.map((color) => {
            const isSelected = colorFilter?.includes(color) ?? false;
            return (
              <Button
                key={color}
                variant="secondary"
                className="h-12 flex items-center justify-center gap-1.5 px-2"
                style={isSelected
                  ? {
                      backgroundColor: COLOR_SWATCHES[color],
                      color: colorTextOn(COLOR_SWATCHES[color]),
                      boxShadow: `inset 0 0 0 1.5px ${colorRingOn(COLOR_SWATCHES[color])}`,
                    }
                  : undefined}
                onClick={() => toggleColor(color)}
                title={colorLabel(color)}
              >
                {!isSelected && (
                  <span
                    className="w-4 h-4 rounded-full border border-black/20 shrink-0"
                    style={{ backgroundColor: COLOR_SWATCHES[color] }}
                  />
                )}
                <span className="text-xs">{colorLabel(color)}</span>
              </Button>
            );
          })}
        </div>
      )}

      {openSheet === 'eggGroup' && (
        <div className="grid grid-cols-3 md:grid-cols-5 gap-1.5">
          {EGG_GROUP_ORDER.map((group) => (
            <Button
              key={group}
              variant={eggGroupFilter?.includes(group) ? 'default' : 'secondary'}
              className="h-10 text-xs px-1"
              onClick={() => toggleEggGroup(group)}
              title={eggGroupLabel(group)}
            >
              {eggGroupLabel(group)}
            </Button>
          ))}
        </div>
      )}

      {openSheet === 'evoStage' && (
        <div className="flex gap-2">
          {[1, 2, 3].map((size) => (
            <Button
              key={size}
              variant={evoLineSizeFilter?.includes(size) ? 'default' : 'secondary'}
              className="flex-1 h-10 text-sm"
              onClick={() => toggleEvoSize(size)}
            >
              {size === 1 && t('browser.stage.1')}
              {size === 2 && t('browser.stage.2')}
              {size === 3 && t('browser.stage.3')}
            </Button>
          ))}
        </div>
      )}

      {openSheet === 'classification' && (
        <FilterChipList items={CATEGORIES} activeId={activeCategory} label={(c) => categoryLabel(c.id)}
          onSelect={(id) => { setCategoryFilter(activeCategory === id ? null : id); setOpenSheet(null); }} />
      )}

      {openSheet === 'places' && (
        <FilterChipList items={PLACES_ORDER.map(id => ARCHETYPES.find(a => a.id === id)!)} activeId={activeArchetype} label={(a) => archetypeLabel(a.id)}
          onSelect={(id) => { setArchetypeFilter(activeArchetype === id ? null : id); setOpenSheet(null); }} />
      )}

      {openSheet === 'archetypes' && (
        <FilterChipList items={ARCHETYPES.filter(a => !PLACES_IDS.has(a.id) && !GAME_MECHANICS_IDS.has(a.id))} activeId={activeArchetype} label={(a) => archetypeLabel(a.id)}
          onSelect={(id) => { setArchetypeFilter(activeArchetype === id ? null : id); setOpenSheet(null); }} />
      )}

      {openSheet === 'gameMechanics' && (
        <FilterChipList items={GAME_MECHANICS_ORDER.map(id => ARCHETYPES.find(a => a.id === id)!)} activeId={activeArchetype} label={(a) => archetypeLabel(a.id)}
          onSelect={(id) => { setArchetypeFilter(activeArchetype === id ? null : id); setOpenSheet(null); }} />
      )}
    </>
  ) : null;

  return (
    <div className="flex flex-col h-full border-l relative bg-background">
      {/* Desktop header: "Adding to: Section" + close */}
      {isDesktop && activeSection && (
        <div className="flex items-center justify-between px-3 sm:px-6 py-2 border-b h-11">
          <h2 className="text-2xl font-extrabold tracking-tight leading-none">
            <span className="text-foreground">{t('browser.addingTo')}</span>
            <span className="text-primary">{sectionName}</span>
          </h2>
          <button type="button"
            onClick={handleDesktopClose}
            className="text-muted-foreground hover:text-foreground cursor-pointer p-1"
          >
            <X size={16} />
          </button>
        </div>
      )}
      {/* Search bar + count + filter chips — non-scrollable */}
      <div ref={browserHeaderRef}>
      <div className="p-3 pb-2">
        <div className="flex items-center gap-2">
          <div className="relative flex-1">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-muted-foreground" />
            <Input
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder={t('browser.search.placeholder')}
              className="pl-9 pr-9"
            />
            {searchQuery && (
              <button type="button"
                onClick={() => setSearchQuery('')}
                className="absolute right-3 top-1/2 -translate-y-1/2 text-muted-foreground hover:text-foreground cursor-pointer"
              >
                <X className="w-4 h-4" />
              </button>
            )}
          </div>
          <span
            className="shrink-0 text-xs text-muted-foreground text-right whitespace-nowrap"
            // The count as a number, for tests that must not depend on how the
            // sentence around it is worded in the active language.
            data-result-count={totalCount}
          >
            {tn('browser.results', totalCount)}
          </span>
        </div>
      </div>

      {/* Filter chip rows */}
      <div className="px-3 pb-2 border-b relative z-[1] shadow-[0_1px_0_0_var(--color-background)] space-y-1.5">
        {/* Row 1: Property filters (Type, Gen, Stages) */}
        <div className={cn("flex items-stretch border-x border-border transition-opacity", isSearching && hasActiveFilters && "opacity-40")}>
          <div className="flex gap-1.5 overflow-x-auto no-scrollbar items-center min-w-0 px-2 py-1">
          {typeFilter && typeFilter.length > 0 ? (
            <>
              {typeFilter.length > 1 && (
                <button type="button"
                  onClick={() => setTypeFilterMode(typeFilterMode === 'any' ? 'all' : 'any')}
                  className="shrink-0 inline-flex items-center px-1.5 py-0.5 rounded-full text-[0.625rem] font-bold bg-muted text-muted-foreground hover:bg-muted/80 cursor-pointer transition-colors"
                >
                  {typeFilterMode === 'any' ? t('browser.modeChip.or') : t('browser.modeChip.and')}
                </button>
              )}
              {typeFilter.map(t => (
                <FilterChip
                  key={t}
                  label={typeLabel(t as TypeName)}
                  onDismiss={() => toggleType(t)}
                  onClick={() => setOpenSheet(openSheet === 'type' ? null : 'type')}
                  className="capitalize text-white"
                  style={{ backgroundColor: TYPE_COLORS[t as keyof typeof TYPE_COLORS] }}
                />
              ))}
            </>
          ) : (
            <EntryChip sheet="type" label={t('browser.chip.type')} onClick={() => setOpenSheet(openSheet === 'type' ? null : 'type')} active={openSheet === 'type'} />
          )}

          {generationFilter && generationFilter.length > 0 ? (
            generationFilter.length <= 3 ? (
              generationFilter.map(g => (
                <FilterChip
                  key={g}
                  label={t('browser.genChip', { gen: g })}
                  onDismiss={() => toggleGeneration(g)}
                  onClick={() => setOpenSheet(openSheet === 'generation' ? null : 'generation')}
                  className="bg-foreground text-background"
                />
              ))
            ) : (
              <FilterChip
                label={tn('browser.count.gens', generationFilter.length)}
                onDismiss={() => setGenerationFilter(null)}
                onClick={() => setOpenSheet(openSheet === 'generation' ? null : 'generation')}
                className="bg-foreground text-background"
              />
            )
          ) : (
            <EntryChip sheet="generation" label={t('browser.chip.gen')} onClick={() => setOpenSheet(openSheet === 'generation' ? null : 'generation')} active={openSheet === 'generation'} />
          )}

          {evoLineSizeFilter ? (
            <FilterChip
              label={t('browser.stageChip', { stages: evoLineSizeFilter.map(s => s === 3 ? '3+' : String(s)).join(',') })}
              onDismiss={() => setEvoLineSizeFilter(null)}
              onClick={() => setOpenSheet(openSheet === 'evoStage' ? null : 'evoStage')}
              className="bg-foreground text-background"
            />
          ) : (
            <EntryChip sheet="evoStage" label={t('browser.chip.stages')} onClick={() => setOpenSheet(openSheet === 'evoStage' ? null : 'evoStage')} active={openSheet === 'evoStage'} />
          )}

          {shapeFilter && shapeFilter.length > 0 ? (
            shapeFilter.length <= 2 ? (
              shapeFilter.map(s => (
                <FilterChip
                  key={s}
                  label={shapeLabel(s as ShapeName)}
                  onDismiss={() => toggleShape(s)}
                  onClick={() => setOpenSheet(openSheet === 'shape' ? null : 'shape')}
                  className="bg-foreground text-background"
                />
              ))
            ) : (
              <FilterChip
                label={tn('browser.count.shapes', shapeFilter.length)}
                onDismiss={() => setShapeFilter(null)}
                onClick={() => setOpenSheet(openSheet === 'shape' ? null : 'shape')}
                className="bg-foreground text-background"
              />
            )
          ) : (
            <EntryChip sheet="shape" label={t('browser.chip.shape')} onClick={() => setOpenSheet(openSheet === 'shape' ? null : 'shape')} active={openSheet === 'shape'} />
          )}

          {colorFilter && colorFilter.length > 0 ? (
            colorFilter.length <= 2 ? (
              colorFilter.map(c => (
                <FilterChip
                  key={c}
                  label={colorLabel(c as ColorName)}
                  onDismiss={() => toggleColor(c)}
                  onClick={() => setOpenSheet(openSheet === 'color' ? null : 'color')}
                  style={{ backgroundColor: COLOR_SWATCHES[c as ColorName], color: colorTextOn(COLOR_SWATCHES[c as ColorName]), boxShadow: `inset 0 0 0 1px ${colorRingOn(COLOR_SWATCHES[c as ColorName])}` }}
                />
              ))
            ) : (
              <FilterChip
                label={tn('browser.count.colors', colorFilter.length)}
                onDismiss={() => setColorFilter(null)}
                onClick={() => setOpenSheet(openSheet === 'color' ? null : 'color')}
                className="bg-foreground text-background"
              />
            )
          ) : (
            <EntryChip sheet="color" label={t('browser.chip.color')} onClick={() => setOpenSheet(openSheet === 'color' ? null : 'color')} active={openSheet === 'color'} />
          )}

          {eggGroupFilter && eggGroupFilter.length > 0 ? (
            eggGroupFilter.length <= 2 ? (
              eggGroupFilter.map(g => (
                <FilterChip
                  key={g}
                  label={eggGroupLabel(g as EggGroupName)}
                  onDismiss={() => toggleEggGroup(g)}
                  onClick={() => setOpenSheet(openSheet === 'eggGroup' ? null : 'eggGroup')}
                  className="bg-foreground text-background"
                />
              ))
            ) : (
              <FilterChip
                label={tn('browser.count.eggGroups', eggGroupFilter.length)}
                onDismiss={() => setEggGroupFilter(null)}
                onClick={() => setOpenSheet(openSheet === 'eggGroup' ? null : 'eggGroup')}
                className="bg-foreground text-background"
              />
            )
          ) : (
            <EntryChip sheet="eggGroup" label={t('browser.chip.eggGroup')} onClick={() => setOpenSheet(openSheet === 'eggGroup' ? null : 'eggGroup')} active={openSheet === 'eggGroup'} />
          )}

          </div>
          {hasActivePropertyFilters && (
            <button type="button"
              onClick={clearPropertyFilters}
              className="shrink-0 self-stretch flex items-center text-[0.625rem] text-muted-foreground hover:text-foreground underline cursor-pointer pr-2 pl-2 bg-background border-l border-border"
            >
              {t('browser.clear')}
            </button>
          )}
        </div>

        {/* Row 2: Browse filters (Classification, Places, Archetypes, Game Mechanics) */}
        <div className={cn("flex items-stretch border-x border-border transition-opacity", isSearching && hasActiveFilters && "opacity-40")}>
          <div className="flex gap-1.5 overflow-x-auto no-scrollbar items-center min-w-0 px-2 py-1">
          {activeCategory ? (
            <FilterChip
              label={categoryName!}
              onDismiss={() => setCategoryFilter(null)}
              onClick={() => setOpenSheet(openSheet === 'classification' ? null : 'classification')}
              className="text-white"
              style={{ backgroundColor: activeCategoryDef?.color }}
            />
          ) : (
            <EntryChip sheet="classification" label={t('browser.chip.classification')} onClick={() => setOpenSheet(openSheet === 'classification' ? null : 'classification')} active={openSheet === 'classification'} />
          )}

          {activeArchetype && PLACES_IDS.has(activeArchetype) ? (
            <FilterChip
              label={archetypeName!}
              onDismiss={() => setArchetypeFilter(null)}
              onClick={() => setOpenSheet(openSheet === 'places' ? null : 'places')}
              className="text-white"
              style={{ backgroundColor: activeArchetypeDef?.color }}
            />
          ) : (
            <EntryChip sheet="places" label={t('browser.chip.places')} onClick={() => setOpenSheet(openSheet === 'places' ? null : 'places')} active={openSheet === 'places'} />
          )}

          {activeArchetype && !PLACES_IDS.has(activeArchetype) && !GAME_MECHANICS_IDS.has(activeArchetype) ? (
            <FilterChip
              label={archetypeName!}
              onDismiss={() => setArchetypeFilter(null)}
              onClick={() => setOpenSheet(openSheet === 'archetypes' ? null : 'archetypes')}
              className="text-white"
              style={{ backgroundColor: activeArchetypeDef?.color }}
            />
          ) : (
            <EntryChip sheet="archetypes" label={t('browser.chip.archetypes')} onClick={() => setOpenSheet(openSheet === 'archetypes' ? null : 'archetypes')} active={openSheet === 'archetypes'} />
          )}

          {activeArchetype && GAME_MECHANICS_IDS.has(activeArchetype) ? (
            <FilterChip
              label={archetypeName!}
              onDismiss={() => setArchetypeFilter(null)}
              onClick={() => setOpenSheet(openSheet === 'gameMechanics' ? null : 'gameMechanics')}
              className="text-white"
              style={{ backgroundColor: activeArchetypeDef?.color }}
            />
          ) : (
            <EntryChip sheet="gameMechanics" label={t('browser.chip.mechanics')} onClick={() => setOpenSheet(openSheet === 'gameMechanics' ? null : 'gameMechanics')} active={openSheet === 'gameMechanics'} />
          )}

          </div>
          {hasActiveBrowseFilters && (
            <button type="button"
              onClick={clearBrowseFilters}
              className="shrink-0 self-stretch flex items-center text-[0.625rem] text-muted-foreground hover:text-foreground underline cursor-pointer pr-2 pl-2 bg-background border-l border-border"
            >
              {t('browser.clear')}
            </button>
          )}
        </div>
      </div>
      </div>

      {/* Desktop inline filter panel */}
      {openSheet && isDesktop && (
        <div className="border-b px-3 py-2 bg-muted/30 max-h-[40vh] overflow-y-auto">
          <div className="flex items-center justify-between mb-2">
            <span className="text-sm font-semibold">{sheetTitle(openSheet)}</span>
            <button type="button" onClick={() => setOpenSheet(null)} className="text-muted-foreground hover:text-foreground cursor-pointer">
              <X size={16} />
            </button>
          </div>
          {filterContent}
        </div>
      )}

      {/* Results area */}
      <div
        ref={resultsScrollRef}
        className="flex-1 min-h-0 overflow-y-auto px-2 pb-2"
        style={{ WebkitOverflowScrolling: 'touch', ...(!isDesktop && { overscrollBehavior: 'contain' }) } as React.CSSProperties}
      >
          {/* Dual-column headers — sticky, left-aligned with 1st and 4th tile columns */}
          {!isSearching && gridCategoryDef?.dualColumns && (
            <div className="sticky top-0 z-30 bg-background border-b">
              <div className="grid grid-cols-2 gap-x-1">
                <div className="w-full text-[0.625rem] font-semibold text-muted-foreground uppercase tracking-wide py-[3px] px-1" style={{ maxWidth: gridMaxW3, marginInline: gridMaxW3 ? 'auto' : undefined }}>
                  {gridCategoryDef.dualColumns.left.label}
                </div>
                <div className="w-full text-[0.625rem] font-semibold text-muted-foreground uppercase tracking-wide py-[3px] px-1" style={{ maxWidth: gridMaxW3, marginInline: gridMaxW3 ? 'auto' : undefined }}>
                  {gridCategoryDef.dualColumns.right.label}
                </div>
              </div>
            </div>
          )}
          {subgroupModels.map((model) => {
            if (model.dualCols) {
              return (
                <div key={model.label} style={SUBGROUP_BLOCK_STYLE}>
                  <div className="sticky top-[22px] z-20 bg-background mt-1 border-b">
                    <div className="grid grid-cols-2 gap-x-1">
                      <div className="w-full text-[0.625rem] font-semibold text-muted-foreground uppercase tracking-wide py-[3px] px-1" style={{ maxWidth: gridMaxW3, marginInline: gridMaxW3 ? 'auto' : undefined }}>
                        {model.label}
                      </div>
                    </div>
                  </div>
                  <div className="grid grid-cols-2 gap-x-1 items-start pt-1">
                    <EvoLineGrid
                      groups={model.leftGroups!}
                      assignedIds={assignedIds}
                      stagedIds={stagedSet}
                      onToggleStage={handleToggleStage}
                      removalStagedIds={removalStagedSet}
                      onToggleRemoval={handleToggleRemoval}
                      cols={3}
                      showGenBadges={showGenBadges}
                    />
                    <EvoLineGrid
                      groups={model.rightGroups!}
                      assignedIds={assignedIds}
                      stagedIds={stagedSet}
                      onToggleStage={handleToggleStage}
                      removalStagedIds={removalStagedSet}
                      onToggleRemoval={handleToggleRemoval}
                      cols={3}
                      showGenBadges={showGenBadges}
                    />
                  </div>
                </div>
              );
            }

            return (
              <div key={model.label} style={SUBGROUP_BLOCK_STYLE}>
                <div className="sticky top-0 z-20 bg-background mt-1 border-b">
                  <div className="text-[0.625rem] font-semibold text-muted-foreground uppercase tracking-wide py-[3px] px-1" style={{ maxWidth: gridMaxW, marginInline: gridMaxW ? 'auto' : undefined }}>
                    {model.label}
                  </div>
                </div>
                <div className="pt-1">
                  <EvoLineGrid
                    groups={model.groups!}
                    assignedIds={assignedIds}
                    stagedIds={stagedSet}
                    onToggleStage={handleToggleStage}
                    removalStagedIds={removalStagedSet}
                    onToggleRemoval={handleToggleRemoval}
                    shinyIds={model.shinyIds}
                    spriteOverrides={model.spriteOverrides}
                    showGenBadges={showGenBadges}
                  />
                </div>
              </div>
            );
          })}
          {groups.length === 0 && (
            <div className="py-12 text-center text-muted-foreground">
              <p>{t('browser.empty.title')}</p>
              <p className="text-sm mt-1">{t('browser.empty.hint')}</p>
            </div>
          )}
          <PageFooter />
      </div>

      {/* Floating action button — add/remove staged pokemon */}
      {(() => {
        const newCount = isDesktop ? 0 : stagedIds.filter(id => !assignedIds.has(id)).length;
        const removeCount = removalStagedIds.length;
        if (newCount === 0 && removeCount === 0) return null;
        return (
          <div className="absolute left-1/2 -translate-x-1/2 z-40 transition-[bottom] duration-200" style={{ bottom: openSheet && !isDesktop && sheetH > 0 ? sheetH + 12 : 12 }}>
            <button type="button"
              onClick={handleSubmitStaged}
              className="bg-primary text-primary-foreground px-5 py-2 rounded-full shadow-lg text-sm font-semibold cursor-pointer hover:bg-primary/90 transition-colors leading-snug text-center"
            >
              {newCount > 0 && removeCount > 0 ? (
                <>
                  <span>{tn('browser.fab.add', newCount)}</span>
                  <br />
                  <span className="text-xs font-normal opacity-90">{t('browser.fab.andRemove', { count: removeCount })}</span>
                </>
              ) : newCount > 0 ? (
                tn('browser.fab.add', newCount)
              ) : (
                tn('browser.fab.remove', removeCount)
              )}
            </button>
          </div>
        );
      })()}

      {/* Filter bottom sheet overlay (mobile only) */}
      {openSheet && !isDesktop && (
        <SheetOverlay onClose={() => setOpenSheet(null)} openSheet={openSheet} onHeight={setSheetH} footer={
          <div className="px-4 py-3 border-t">
            <Button className="w-full" onClick={() => setOpenSheet(null)}>
              {t('browser.showResults', { count: totalCount })}
            </Button>
          </div>
        }>
          {filterContent}
        </SheetOverlay>
      )}
    </div>
  );
}

/** Sheet overlay — non-modal bottom sheet that allows interaction with content behind */
function SheetOverlay({ onClose, openSheet, children, footer, onHeight }: {
  onClose: () => void;
  openSheet: string;
  children: React.ReactNode;
  footer?: React.ReactNode;
  onHeight?: (h: number) => void;
}) {
  const headerRef = useRef<HTMLDivElement>(null);
  const footerRef = useRef<HTMLDivElement>(null);
  const sheetRef = useRef<HTMLDivElement>(null);

  // Block touchmove on non-scrollable areas (header, footer) to prevent pull-to-refresh
  useEffect(() => {
    const els = [headerRef.current, footerRef.current].filter(Boolean) as HTMLElement[];
    const block = (e: TouchEvent) => e.preventDefault();
    els.forEach(el => el.addEventListener('touchmove', block, { passive: false }));
    return () => { els.forEach(el => el.removeEventListener('touchmove', block)); };
  }, []);

  useLayoutEffect(() => {
    if (sheetRef.current && onHeight) onHeight(sheetRef.current.offsetHeight);
    return () => { onHeight?.(0); };
  }, [openSheet, onHeight]);

  return (
    <div className="absolute inset-x-0 bottom-0 z-50 pointer-events-none">
      <div ref={sheetRef} className="pointer-events-auto bg-background border-t rounded-t-xl shadow-2xl max-h-[50vh] flex flex-col">
        {/* Sheet header */}
        <div ref={headerRef} className="flex items-center justify-between px-4 py-3 border-b">
          <span className="text-sm font-semibold">
            {sheetTitle(openSheet as Exclude<FilterSheet, null>)}
          </span>
          <button type="button" onClick={onClose} className="text-muted-foreground hover:text-foreground cursor-pointer">
            <X size={16} />
          </button>
        </div>

        {/* Sheet body — natural scroll */}
        <div
          className="flex-1 min-h-0 overflow-y-auto p-3"
          style={{ WebkitOverflowScrolling: 'touch', overscrollBehavior: 'contain' } as React.CSSProperties}
        >
          {children}
        </div>
        <div ref={footerRef}>{footer}</div>
      </div>
    </div>
  );
}

/** Entry-point chip — opens a filter sheet */
function EntryChip({ label, onClick, active, sheet }: { label: string; onClick: () => void; active: boolean; sheet: FilterSheet }) {
  return (
    <button type="button"
      onClick={onClick}
      // Stable handle for the extraction-coverage spec, which opens every panel
      // in turn — the label is translated and the pseudo-locale mangles it.
      data-filter-chip={sheet}
      className={cn(
        'shrink-0 inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-medium cursor-pointer border transition-colors',
        active
          ? 'border-primary text-primary bg-primary/5'
          : 'border-border text-muted-foreground hover:border-foreground/30 hover:text-foreground'
      )}
    >
      {label}
      <ChevronDown size={12} className={cn('transition-transform', active && 'rotate-180')} />
    </button>
  );
}

/** Active filter chip — shows value with dismiss */
function FilterChip({
  label, onDismiss, onClick, className, style,
}: {
  label: string; onDismiss: () => void; onClick: () => void; className?: string; style?: React.CSSProperties;
}) {
  return (
    <span
      className={cn(
        'shrink-0 inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-medium',
        className
      )}
      style={style}
    >
      <button type="button" onClick={onClick} className="cursor-pointer">{label}</button>
      <button type="button" onClick={(e) => { e.stopPropagation(); onDismiss(); }} className="hover:opacity-70 cursor-pointer">
        <X size={10} />
      </button>
    </span>
  );
}
